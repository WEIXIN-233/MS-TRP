CIT = re.compile(r'(\[\d+\])')

def set_para_text(p, new_text):
    # 以原首段 run 的 rPr 作为字体模板（去掉 vertAlign 影响）
    template_rpr = None
    runs = p.runs
    if runs:
        rpr = runs[0]._element.find(qn('w:rPr'))
        if rpr is not None:
            template_rpr = copy.deepcopy(rpr)
    # 移除全部现有 run
    for r in list(runs):
        r._element.getparent().remove(r._element)
    # 按引用标记切分，重建 run
    for seg in CIT.split(new_text):
        if seg == '':
            continue
        run = p.add_run(seg)
        el = run._element
        old_rpr = el.find(qn('w:rPr'))
        if old_rpr is not None:
            el.remove(old_rpr)
        if template_rpr is not None:
            rpr = copy.deepcopy(template_rpr)
            el.insert(0, rpr)
        else:
            rpr = None
        if CIT.fullmatch(seg):
            # 上标引用
            if rpr is None:
                run.font.superscript = True
            else:
                va = rpr.find(qn('w:vertAlign'))
                if va is None:
                    va = OxmlElement('w:vertAlign')
                    rpr.append(va)
                va.set(qn('w:val'), 'superscript')

