def main():
    with io.open(P, encoding="utf-8", newline="") as f:
        s = f.read().replace("\r\n", "\n")
    n = 0
    for old, new in REPS:
        if old not in s:
            print("MISS:", old[:50])
            continue
        s = s.replace(old, new, 1)
        n += 1
    with io.open(P, "w", encoding="utf-8", newline="\r\n") as f:
        f.write(s)
    print(f"patched {n}/{len(REPS)}")


